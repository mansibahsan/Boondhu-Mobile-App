class MealModel {
  final String id;
  final String name;
  final String kitchenName;
  final String price;
  final double rating;
  final String time;
  final String description;

  MealModel({
    required this.id,
    required this.name,
    required this.kitchenName,
    required this.price,
    required this.rating,
    required this.time,
    required this.description,
  });
}
